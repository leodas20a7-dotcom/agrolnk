export const COMMODITY_GROUPS = [
  'All Groups',
  'Vegetables',
  'Fruits',
  'Food Grains / Cereals',
  'Oilseeds',
  'Spices',
  'Medicinal Plants',
  'Misc / Plantation Crops',
];

const taxonomyMap = new Map();
COMMODITY_TAXONOMY.forEach((item) => {
  taxonomyMap.set(item.name.toLowerCase(), item);
});

export function getAllCommodityNames() {
  return COMMODITY_TAXONOMY.map((c) => c.name);
}

export function getCommodityGroups() {
  return COMMODITY_GROUPS;
}

export function getCommoditiesByGroup(group) {
  if (!group || group === 'All Groups') return getAllCommodityNames();
  return COMMODITY_TAXONOMY
    .filter((c) => c.group.toLowerCase() === group.toLowerCase())
    .map((c) => c.name);
}

export function getVarietiesForCommodity(commodityName) {
  if (!commodityName) return [];
  const found = taxonomyMap.get(commodityName.trim().toLowerCase());
  if (found && Array.isArray(found.varieties) && found.varieties.length > 0) {
    return found.varieties;
  }
  return ['Standard / FAQ Lot'];
}

export function hasVarieties(commodityName) {
  if (!commodityName) return false;
  const found = taxonomyMap.get(commodityName.trim().toLowerCase());
  return Boolean(found && Array.isArray(found.varieties) && found.varieties.length > 0);
}

export function getCommodityDetails(commodityName) {
  if (!commodityName) return null;
  return taxonomyMap.get(commodityName.trim().toLowerCase()) || null;
}

export function getCommodityGroup(commodityName) {
  const details = getCommodityDetails(commodityName);
  return details?.group || 'Agriculture';
}
